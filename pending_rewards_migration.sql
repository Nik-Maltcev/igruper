-- Отложенное начисление наград за гоночный день.
-- В момент "ЗАПУСТИТЬ ГОНКИ" деньги/очки/призы НЕ попадают на баланс игрока:
-- они копятся в pending_rewards (JSON вида
--   {"day": 12, "money": 5000, "points": 30, "prizes": [...], "notes": ["..."]})
-- и выдаются игроку, когда он досмотрит результаты дня (кнопка "ЗАВЕРШИТЬ ДЕНЬ"
-- на экране результатов), а если он их не открыл — автоматически при переходе
-- комнаты к следующему дню (в т.ч. по автопереводу в 22:00).
ALTER TABLE public.room_players
  ADD COLUMN IF NOT EXISTS pending_rewards JSONB NULL;
